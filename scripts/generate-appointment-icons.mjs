// Writes src/app/shared/appointment-icon-svgs.ts with the SVG of every icon listed in
// APPOINTMENT_ICONS. The SVGs are copied as literals rather than imported from
// @ng-icons/lucide: that package is a single module, and since the app shell imports
// its UI icons from it, importing the appointment icons from it too would pull them
// into the initial bundle instead of a lazy chunk.
//
// Run after changing APPOINTMENT_ICONS or upgrading @ng-icons/lucide:
//   npm run icons:generate
import { readFileSync, writeFileSync } from 'node:fs';
import * as lucide from '@ng-icons/lucide';

const source = new URL('../src/app/shared/appointment-style.ts', import.meta.url);
const target = new URL('../src/app/shared/appointment-icon-svgs.ts', import.meta.url);

const names = [
  ...new Set([...readFileSync(source, 'utf8').matchAll(/value: '(lucide\w+)'/g)].map((m) => m[1])),
].sort();

const missing = names.filter((name) => typeof lucide[name] !== 'string');
if (missing.length) {
  console.error(`Not in @ng-icons/lucide: ${missing.join(', ')}`);
  process.exit(1);
}

const entries = names.map((name) => `  ${name}: ${JSON.stringify(lucide[name])},`).join('\n');
writeFileSync(
  target,
  `// Generated by \`npm run icons:generate\` from @ng-icons/lucide. Do not edit by hand.
// Only ever imported dynamically (see \`loadAppointmentIcon\` in icons.ts), so these
// paths end up in their own chunk instead of the initial bundle.
export const APPOINTMENT_ICON_SVGS: Record<string, string> = {
${entries}
};
`,
);
console.log(`Wrote ${names.length} icons to ${target.pathname}`);
